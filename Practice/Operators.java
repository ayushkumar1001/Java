public class Operators {

    public static void main(String args[])
    {
        int a=10, b=5;

        //Addition
        System.out.println("a + b = " + (a+b));

        //substraction
        System.out.println("a  - b = " + (a-b));

        //multiplaction
        System.out.println("a * b =" + (a*b));

        //Division
        System.out.println("a / b = " + (a / b));

        //Modulus
        System.out.println("a % b = " + (a%b));
    }
}